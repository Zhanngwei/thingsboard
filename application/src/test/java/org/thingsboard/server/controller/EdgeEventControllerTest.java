        List<Long> partitions = partitioningRepository.fetchPartitions("edge_event");
        assertThat(partitions).contains(partitionStartTs);

        edgeEventsCleanUpService.cleanUp();
        // DAO 调用是数据库访问边界，事务和缓存一致性由上层服务约定控制。
