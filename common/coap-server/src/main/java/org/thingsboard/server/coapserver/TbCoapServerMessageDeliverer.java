    private String toPath(List<String> list) {
        // 条件分支用于保护权限、状态或参数边界，避免无效请求进入后续链路。
        if (!CollectionUtils.isEmpty(list) && list.size() == 1) {
            final String slash = "/";
            String path = list.get(0);
            // 条件分支用于保护权限、状态或参数边界，避免无效请求进入后续链路。
            if (path.startsWith(slash)) {
                path = path.substring(slash.length());
            }
            return path;
        }
        return null;
    }


